);
CREATE TABLE IF NOT EXISTS service_metrics (
  service_id BIGINT PRIMARY KEY REFERENCES services(id) ON DELETE CASCADE CHECK(service_id>0),
  total_inspected BIGINT NOT NULL DEFAULT 0,
  total_blocked BIGINT NOT NULL DEFAULT 0,
  total_latency_ms DOUBLE PRECISION NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK(total_inspected>=0 AND total_blocked>=0 AND total_blocked<=total_inspected AND total_latency_ms>=0)
);

CREATE OR REPLACE FUNCTION sqlishield_protect_default_rules() RETURNS trigger LANGUAGE plpgsql AS $body$
BEGIN
  IF OLD.service_id=0 OR (TG_OP='UPDATE' AND NEW.service_id=0) THEN RAISE EXCEPTION 'Shared default rules are read-only'; END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $body$;
DROP TRIGGER IF EXISTS sqlishield_default_rules_guard ON rules;
CREATE TRIGGER sqlishield_default_rules_guard BEFORE UPDATE OR DELETE ON rules FOR EACH ROW EXECUTE FUNCTION sqlishield_protect_default_rules();
