CREATE TABLE IF NOT EXISTS rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id BIGINT NOT NULL REFERENCES services(id),
  name VARCHAR(150) NOT NULL,
  description TEXT,
  match_type VARCHAR(20) NOT NULL CHECK (match_type IN ('regex','keyword')),
  pattern TEXT NOT NULL CHECK (length(pattern)>0 AND length(pattern)<=1000),
  score INTEGER NOT NULL CHECK (score BETWEEN 1 AND 100),
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(service_id,name)
);
ALTER TABLE rules ADD COLUMN IF NOT EXISTS description TEXT;
ALTER TABLE rules ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
CREATE UNIQUE INDEX IF NOT EXISTS rules_service_name_unique ON rules(service_id,name);
CREATE INDEX IF NOT EXISTS rules_enabled_service_idx ON rules(service_id,enabled);

